// Pure Three.js Viewport Component for 100% Reliable WebGL Rendering
function ThreeModelViewport({
  model,
  selectedPartId,
  onSelectPart,
  autoRotate,
  wireframeAll,
  lightingPreset
}: {
  model: Generated3DModel;
  selectedPartId: string | null;
  onSelectPart: (id: string) => void;
  autoRotate: boolean;
  wireframeAll: boolean;
  lightingPreset: "neon" | "studio" | "matrix";
}) {
  const containerRef = useRef<HTMLDivElement>(null);
  const canvasRef = useRef<HTMLCanvasElement>(null);

  // Keep state refs for animation loop
  const stateRef = useRef({
    autoRotate,
    wireframeAll,
    selectedPartId,
    model,
    lightingPreset
  });

  useEffect(() => {
    stateRef.current = {
      autoRotate,
      wireframeAll,
      selectedPartId,
      model,
      lightingPreset
    };
  }, [autoRotate, wireframeAll, selectedPartId, model, lightingPreset]);

  useEffect(() => {
    const container = containerRef.current;
    const canvas = canvasRef.current;
    if (!container || !canvas) return;

    let width = container.clientWidth || 800;
    let height = container.clientHeight || 600;

    // Renderer
    const renderer = new THREE.WebGLRenderer({
      canvas,
      antialias: true,
      alpha: true,
      preserveDrawingBuffer: true,
      powerPreference: "high-performance"
    });
    renderer.setPixelRatio(Math.min(window.devicePixelRatio || 1, 2));
    renderer.setSize(width, height);
    renderer.toneMapping = THREE.ACESFilmicToneMapping;
    renderer.toneMappingExposure = 1.1;

    // Scene
    const scene = new THREE.Scene();
    scene.background = new THREE.Color("#0c081e");

    // Camera
    const camera = new THREE.PerspectiveCamera(45, width / height, 0.1, 100);
    camera.position.set(0, 1.1, 5.2);
    camera.lookAt(0, 0.35, 0);

    // Tech Floor Grid
    const grid = new THREE.GridHelper(16, 16, 0x7c3aed, 0x312e81);
    grid.position.set(0, -1.3, 0);
    scene.add(grid);

    // Lights
    const ambientLight = new THREE.AmbientLight(0xffffff, 0.7);
    scene.add(ambientLight);

    const dirLight1 = new THREE.DirectionalLight(0xe0e7ff, 1.8);
    dirLight1.position.set(5, 8, 5);
    scene.add(dirLight1);

    const pointLight1 = new THREE.PointLight(0xa855f7, 3.0, 20);
    pointLight1.position.set(-4, 3, -3);
    scene.add(pointLight1);

    const pointLight2 = new THREE.PointLight(0x06b6d4, 2.5, 20);
    pointLight2.position.set(4, -2, 2);
    scene.add(pointLight2);

    const pointLight3 = new THREE.PointLight(0xec4899, 1.5, 20);
    pointLight3.position.set(0, 4, 3);
    scene.add(pointLight3);

    // Model Group
    const modelGroup = new THREE.Group();
    scene.add(modelGroup);

    // Build Meshes function
    const meshesMap = new Map<string, THREE.Mesh>();
    const outlineMap = new Map<string, THREE.LineSegments>();

    const rebuildMeshes = (currentModel: Generated3DModel, activeSelectedId: string | null, isWireframe: boolean) => {
      // Clear previous children
      while (modelGroup.children.length > 0) {
        modelGroup.remove(modelGroup.children[0]);
      }
      meshesMap.clear();
      outlineMap.clear();

      currentModel.parts.forEach((part) => {
        let geo: THREE.BufferGeometry;
        if (part.type === "box") {
          geo = new THREE.BoxGeometry(part.args[0], part.args[1], part.args[2]);
        } else if (part.type === "sphere") {
          geo = new THREE.SphereGeometry(part.args[0], part.args[1] || 24, part.args[2] || 24);
        } else if (part.type === "cylinder") {
          geo = new THREE.CylinderGeometry(part.args[0], part.args[1], part.args[2], part.args[3] || 16);
        } else if (part.type === "cone") {
          geo = new THREE.ConeGeometry(part.args[0], part.args[1], part.args[2] || 16);
        } else if (part.type === "torus") {
          geo = new THREE.TorusGeometry(part.args[0], part.args[1], part.args[2] || 16, part.args[3] || 32);
        } else {
          geo = new THREE.BoxGeometry(1, 1, 1);
        }

        const isSelected = part.id === activeSelectedId;
        const mat = new THREE.MeshStandardMaterial({
          color: isSelected ? new THREE.Color("#ec4899") : new THREE.Color(part.color),
          emissive: isSelected ? new THREE.Color("#f43f5e") : new THREE.Color(part.emissive || "#000000"),
          emissiveIntensity: isSelected ? 1.0 : (part.emissiveIntensity || 0),
          metalness: part.metalness ?? 0.7,
          roughness: part.roughness ?? 0.3,
          wireframe: isWireframe || Boolean(part.wireframe)
        });

        const mesh = new THREE.Mesh(geo, mat);
        mesh.position.set(...part.position);
        if (part.rotation) {
          mesh.rotation.set(...part.rotation);
        }
        mesh.userData = { id: part.id, name: part.name };

        modelGroup.add(mesh);
        meshesMap.set(part.id, mesh);

        if (isSelected) {
          const edges = new THREE.EdgesGeometry(geo);
          const line = new THREE.LineSegments(edges, new THREE.LineBasicMaterial({ color: 0xffffff, linewidth: 2 }));
          line.position.copy(mesh.position);
          line.rotation.copy(mesh.rotation);
          line.scale.set(1.03, 1.03, 1.03);
          modelGroup.add(line);
          outlineMap.set(part.id, line);
        }
      });
    };

    rebuildMeshes(model, selectedPartId, wireframeAll);

    // Orbit & Camera Drag controls
    let isDragging = false;
    let prevMouseX = 0;
    let prevMouseY = 0;
    let sphericalTheta = 0;
    let sphericalPhi = Math.PI / 2.3;
    let sphericalRadius = 5.2;

    const updateCameraFromAngles = () => {
      camera.position.x = sphericalRadius * Math.sin(sphericalPhi) * Math.sin(sphericalTheta);
      camera.position.y = sphericalRadius * Math.cos(sphericalPhi) + 0.3;
      camera.position.z = sphericalRadius * Math.sin(sphericalPhi) * Math.cos(sphericalTheta);
      camera.lookAt(0, 0.3, 0);
    };

    const onMouseDown = (e: MouseEvent) => {
      isDragging = true;
      prevMouseX = e.clientX;
      prevMouseY = e.clientY;
    };

    const onMouseMove = (e: MouseEvent) => {
      if (!isDragging) return;
      const deltaX = e.clientX - prevMouseX;
      const deltaY = e.clientY - prevMouseY;
      prevMouseX = e.clientX;
      prevMouseY = e.clientY;

      sphericalTheta -= deltaX * 0.008;
      sphericalPhi -= deltaY * 0.008;
      sphericalPhi = Math.max(0.2, Math.min(Math.PI / 2 + 0.2, sphericalPhi));
      updateCameraFromAngles();
    };

    const onMouseUp = () => {
      isDragging = false;
    };

    const onWheel = (e: WheelEvent) => {
      e.preventDefault();
      sphericalRadius += e.deltaY * 0.003;
      sphericalRadius = Math.max(1.8, Math.min(8.0, sphericalRadius));
      updateCameraFromAngles();
    };

    // Raycaster for clicking parts
    const raycaster = new THREE.Raycaster();
    const mouseVec = new THREE.Vector2();

    const onClick = (e: MouseEvent) => {
      const rect = canvas.getBoundingClientRect();
      mouseVec.x = ((e.clientX - rect.left) / rect.width) * 2 - 1;
      mouseVec.y = -((e.clientY - rect.top) / rect.height) * 2 + 1;

      raycaster.setFromCamera(mouseVec, camera);
      const intersects = raycaster.intersectObjects(modelGroup.children, true);
      if (intersects.length > 0) {
        const hit = intersects[0].object as THREE.Mesh;
        if (hit.userData && hit.userData.id) {
          onSelectPart(hit.userData.id);
        }
      }
    };

    canvas.addEventListener("mousedown", onMouseDown);
    window.addEventListener("mousemove", onMouseMove);
    window.addEventListener("mouseup", onMouseUp);
    canvas.addEventListener("wheel", onWheel, { passive: false });
    canvas.addEventListener("click", onClick);

    // Resize handler
    const onResize = () => {
      if (!container) return;
      width = container.clientWidth || 800;
      height = container.clientHeight || 600;
      camera.aspect = width / height;
      camera.updateProjectionMatrix();
      renderer.setSize(width, height);
    };

    window.addEventListener("resize", onResize);
    const resizeObserver = new ResizeObserver(onResize);
    resizeObserver.observe(container);

    // Animation Loop
    let animId: number;
    let clock = new THREE.Clock();
    let currentModelRef = model;
    let currentSelectedRef = selectedPartId;
    let currentWireframeRef = wireframeAll;
    let currentPresetRef = lightingPreset;

    const animate = () => {
      animId = requestAnimationFrame(animate);
      const elapsedTime = clock.getElapsedTime();

      // Check if external props changed
      if (
        stateRef.current.model !== currentModelRef ||
        stateRef.current.selectedPartId !== currentSelectedRef ||
        stateRef.current.wireframeAll !== currentWireframeRef
      ) {
        currentModelRef = stateRef.current.model;
        currentSelectedRef = stateRef.current.selectedPartId;
        currentWireframeRef = stateRef.current.wireframeAll;
        rebuildMeshes(currentModelRef, currentSelectedRef, currentWireframeRef);
      }

      if (stateRef.current.lightingPreset !== currentPresetRef) {
        currentPresetRef = stateRef.current.lightingPreset;
        if (currentPresetRef === "neon") {
          pointLight1.color.set(0xa855f7);
          pointLight2.color.set(0x06b6d4);
          pointLight3.color.set(0xec4899);
        } else if (currentPresetRef === "studio") {
          pointLight1.color.set(0xffffff);
          pointLight2.color.set(0x94a3b8);
          pointLight3.color.set(0xffffff);
        } else if (currentPresetRef === "matrix") {
          pointLight1.color.set(0x10b981);
          pointLight2.color.set(0x059669);
          pointLight3.color.set(0x34d399);
        }
      }

      if (stateRef.current.autoRotate && !isDragging) {
        modelGroup.rotation.y += 0.015;
      }

      modelGroup.position.y = Math.sin(elapsedTime * 1.6) * 0.08;

      renderer.render(scene, camera);
    };

    animate();

    return () => {
      cancelAnimationFrame(animId);
      resizeObserver.disconnect();
      window.removeEventListener("resize", onResize);
      canvas.removeEventListener("mousedown", onMouseDown);
      window.removeEventListener("mousemove", onMouseMove);
      window.removeEventListener("mouseup", onMouseUp);
      canvas.removeEventListener("wheel", onWheel);
      canvas.removeEventListener("click", onClick);
      renderer.dispose();
    };
  }, []);

  return (
    <div ref={containerRef} className="absolute inset-0 w-full h-full overflow-hidden">
      <canvas ref={canvasRef} className="w-full h-full block cursor-grab active:cursor-grabbing" />
    </div>
  );
}

