// Procedural Mesh Renderer Component
function RenderModelPart({ part, isSelected, onClick }: { part: ModelPart; isSelected: boolean; onClick: () => void }) {
  const meshRef = useRef<THREE.Mesh>(null);

  return (
    <mesh
      ref={meshRef}
      position={part.position}
      rotation={part.rotation || [0, 0, 0]}
      onClick={(e) => {
        e.stopPropagation();
        onClick();
      }}
    >
      {part.type === "box" && <boxGeometry args={part.args as [number, number, number]} />}
      {part.type === "sphere" && <sphereGeometry args={part.args as [number, number, number]} />}
      {part.type === "cylinder" && <cylinderGeometry args={part.args as [number, number, number, number]} />}
      {part.type === "cone" && <coneGeometry args={part.args as [number, number, number]} />}
      {part.type === "torus" && <torusGeometry args={part.args as [number, number, number, number]} />}
      <meshStandardMaterial
        color={part.color}
        emissive={part.emissive || "#000000"}
        emissiveIntensity={part.emissiveIntensity || 0}
        metalness={part.metalness ?? 0.5}
        roughness={part.roughness ?? 0.5}
        wireframe={part.wireframe || false}
      />
      {isSelected && (
        <meshBasicMaterial
          wireframe
          color="#ffffff"
          transparent
          opacity={0.8}
        />
      )}
    </mesh>
  );
}

// Model Group with Hover & Animation
function AnimatedModelScene({ model, selectedPartId, onSelectPart, autoRotate }: {
  model: Generated3DModel;
  selectedPartId: string | null;
  onSelectPart: (id: string) => void;
  autoRotate: boolean;
}) {
  const groupRef = useRef<THREE.Group>(null);

  useFrame((state, delta) => {
    if (groupRef.current && autoRotate) {
      groupRef.current.rotation.y += delta * 0.45;
    }
  });

  return (
    <Float speed={2} rotationIntensity={0.2} floatIntensity={0.4}>
      <group ref={groupRef} position={[0, 0, 0]}>
        {model.parts.map((part) => (
          <RenderModelPart
            key={part.id}
            part={part}
            isSelected={selectedPartId === part.id}
            onClick={() => onSelectPart(part.id)}
          />
        ))}
      </group>
    </Float>
  );
}

